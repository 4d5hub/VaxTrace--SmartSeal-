const { JSDOM, VirtualConsole } = require("jsdom");
const fs = require("fs");
const html = fs.readFileSync(require("path").join(__dirname, "..", "index.html") + "", "utf8");
const errors = [];
const vc = new VirtualConsole();
vc.on("jsdomError", e => errors.push("jsdomError: " + (e.detail && e.detail.message || e.message)));
vc.on("error", e => errors.push("console.error: " + e));
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const dom = new JSDOM(html, { runScripts: "dangerously", pretendToBeVisual: true, virtualConsole: vc, url: "file:///dashboard/index.html",
    beforeParse(w) { Object.defineProperty(w, "crypto", { value: require("crypto").webcrypto, configurable: true }); w.fetch = (u, o) => fetch(u, o); w.AbortController = AbortController; w.TextEncoder = TextEncoder; w.matchMedia = () => ({ matches: true });
      w.structuredClone = structuredClone; w.URL.createObjectURL = () => "blob:x"; w.HTMLElement.prototype.scrollIntoView = () => {}; } });
  const w = dom.window, d = w.document, $ = id => d.getElementById(id);
  await sleep(2500);
  const out = [];
  const check = (name, cond) => { out.push((cond ? "PASS " : "FAIL ") + name); };
  check("simulation booted (oled text present)", $("oled").textContent.includes("SEAL-A1"));
  check("India case study present in simulation mode", !!$("india") && $("india").closest("#simRoot") !== null);
  $("lvKey").value = "stack-key";
  $("mLive").click(); await sleep(2500);
  check("badge shows CONNECTED", $("lvConn").textContent.includes("CONNECTED") && !$("lvConn").textContent.includes("DISCONNECTED"));
  check("sim hidden, live shown", $("simRoot").hidden && !$("liveRoot").hidden);
  check("shipment select filled", $("lvShip").textContent.includes("SHP-001"));
  check("tab1 hardware: OLED + key + counter", $("lvBody").textContent.includes("rec#8") && $("lvBody").textContent.includes("software stand-in"));
  const tabs = [...d.querySelectorAll("#lvTabs button")];
  const open = async i => { tabs[i].click(); await sleep(2500); return $("lvBody").textContent; };
  let t = await open(1); check("tab2 records table", t.includes("prevHash") && t.includes("5.20"));
  t = await open(2); check("tab3 integrity checks + batches + merkle tree", t.includes("Merkle roots match anchored roots") && t.includes("ANCHORED") && $("lvBody").querySelectorAll(".tree .row").length >= 3);
  t = await open(3); check("tab4 custody: 3 handoffs, both signed", t.includes("3 of 3") && (t.match(/signed/g) || []).length >= 6);
  d.querySelector("[data-h='reuse_nonce']").click(); await sleep(2500);
  check("tab4 shows contract-style rejection code after a bad handoff", $("lvBody").textContent.includes("ROUTE_COMPLETE") || $("lvBody").textContent.includes("NONCE_REUSED"));
  t = await open(4); check("tab5 blockchain: validators measured as unreachable (no fake quorum) + blocks + on-chain shipment", t.includes("No quorum") && t.includes("Latest blocks") && t.includes("anchored batches") && t.includes("Batch anchors on the ledger"));
  t = await open(5); check("tab6 attacks: run button present", !!$("lvAtkRun"));
  t = await open(6); check("tab7 verifier: run buttons", !!$("lvVer"));
  $("lvVer").click(); await sleep(3500);
  t = $("lvBody").textContent; check("tab7 verdict ACCEPT with 25 checks", !!d.querySelector(".verdict.ACCEPT") && t.includes("Produce verdict") && t.includes("Checks (25)"));
  $("lvVerFin").click(); await sleep(4500);
  t = $("lvBody").textContent; check("finalized on-chain: verdict record shown", t.includes("On-chain verdict") && t.includes("ACCEPT"));
  await open(7); check("tab8 India case study moved into live tab", $("lvIndia").contains($("india")) && !$("lvIndia").hidden);
  $("mSim").click(); await sleep(800);
  check("India panel returned to simulation layout", $("simRoot").contains($("india")) && !$("simRoot").hidden);
  $("mLive").click(); await sleep(300);
  $("lvUrl").value = "http://127.0.0.1:9"; $("lvUrl").dispatchEvent(new w.Event("change")); await sleep(4000);
  check("backend offline: badge DISCONNECTED and page does not crash", $("lvConn").textContent.includes("DISCONNECTED") && ($("lvBody").textContent.includes("not reachable") || $("lvBody").hidden));
  $("mSim").click(); await sleep(500);
  check("simulation still alive after offline live mode", $("oled").textContent.length > 10);
  console.log(out.join("\n"));
  console.log(errors.length ? "JS ERRORS:\n" + errors.slice(0, 6).join("\n") : "no JS errors");
  process.exit(out.some(l => l.startsWith("FAIL")) ? 1 : 0);
})();
